// Whether a certificate's enhanced key usage extension names an OID
static bool cert_has_eku(PCCERT_CONTEXT cert, const char *oid) {
	DWORD size = 0;
	bool found = false;

	if (CertGetEnhancedKeyUsage(cert, CERT_FIND_EXT_ONLY_ENHKEY_USAGE_FLAG, NULL, &size) == false || size == 0)
		return false;

	CERT_ENHKEY_USAGE *eku = (CERT_ENHKEY_USAGE *)HeapAlloc(GetProcessHeap(), 0, size);
	if (eku != NULL) {
		if (CertGetEnhancedKeyUsage(cert, CERT_FIND_EXT_ONLY_ENHKEY_USAGE_FLAG, eku, &size))
			for (DWORD i = 0; i < eku->cUsageIdentifier; i++)
				if (strcmp(eku->rgpszUsageIdentifier[i], oid) == 0)
					found = true;
		HeapFree(GetProcessHeap(), 0, eku);
	}

	return found;
}

// The self-signed ECDSA P-256 certificate on a new key of the key storage provider: it verifies
// with its own public key, carries the algorithms and extensions it was made with, and its
// private key is reachable through the certificate as a CNG key. A changed signature does not
// verify; the key can be deleted through the certificate.
void selfsign_test() {
	static const UCHAR p256_oid[] = {0x06, 0x08, 0x2a, 0x86, 0x48, 0xce, 0x3d, 0x03, 0x01, 0x07};
	wchar_t dns[256];
	UINT scope = coretest_scope();

	coretest_info("scope: %s", coretest_scope_name());

	PCCERT_CONTEXT cert = CryptoCertCreateSelfSigned(L"CN=Ranz coretest, O=Ranz VPN", L"coretest.ranz.invalid", NULL, 30, scope);
	if (coretest_check(cert != NULL, "certificate created on a new ECDSA P-256 key of the software KSP") == false)
		return;

	CERT_INFO *info = cert->pCertInfo;
	coretest_check(CryptoCertVerifySelfSigned(cert), "the signature verifies with the certificate's own public key");
	coretest_check(strcmp(info->SignatureAlgorithm.pszObjId, szOID_ECDSA_SHA256) == 0, "signature algorithm ecdsa-with-SHA256 (1.2.840.10045.4.3.2)");
	coretest_check(strcmp(info->SubjectPublicKeyInfo.Algorithm.pszObjId, szOID_ECC_PUBLIC_KEY) == 0 &&
	                   info->SubjectPublicKeyInfo.Algorithm.Parameters.cbData == sizeof(p256_oid) &&
	                   memcmp(info->SubjectPublicKeyInfo.Algorithm.Parameters.pbData, p256_oid, sizeof(p256_oid)) == 0,
	               "public key id-ecPublicKey on prime256v1 (1.2.840.10045.3.1.7)");
	coretest_check(info->SubjectPublicKeyInfo.PublicKey.cbData == 65 && info->SubjectPublicKeyInfo.PublicKey.pbData[0] == 0x04,
	               "uncompressed 65-byte P-256 point");
	coretest_check(info->dwVersion == CERT_V3, "X.509 version 3");
	coretest_check(cert_has_eku(cert, szOID_PKIX_KP_SERVER_AUTH) && cert_has_eku(cert, szOID_PKIX_KP_CLIENT_AUTH), "server and client authentication usage");

	CERT_EXTENSION *ku = CertFindExtension(szOID_KEY_USAGE, info->cExtension, info->rgExtension);
	coretest_check(ku != NULL && ku->fCritical, "key usage extension, critical");
	coretest_check(CertGetNameStringW(cert, CERT_NAME_DNS_TYPE, 0, NULL, dns, 256) > 1 && wcscmp(dns, L"coretest.ranz.invalid") == 0,
	               "subject alternative name dNSName coretest.ranz.invalid");

	// Valid from a day ago for 30 days: 31 days, rounded to whole days (X.509 times have seconds)
	ULARGE_INTEGER from, to;
	from.LowPart = info->NotBefore.dwLowDateTime;
	from.HighPart = info->NotBefore.dwHighDateTime;
	to.LowPart = info->NotAfter.dwLowDateTime;
	to.HighPart = info->NotAfter.dwHighDateTime;
	ULONGLONG day = 24ULL * 60 * 60 * 10000000;
	coretest_check(to.QuadPart > from.QuadPart && (to.QuadPart - from.QuadPart + day / 2) / day == 31, "valid from a day ago for 30 days");

	coretest_check(CryptoCertHasKspKey(cert), "the private key is a CNG key, reached through the certificate");

	// One bit of the signature changed: the certificate no longer verifies
	BYTE *copy = (BYTE *)HeapAlloc(GetProcessHeap(), 0, cert->cbCertEncoded);
	if (copy != NULL) {
		CopyMemory(copy, cert->pbCertEncoded, cert->cbCertEncoded);
		copy[cert->cbCertEncoded - 1] ^= 0x01;
		PCCERT_CONTEXT bad = CertCreateCertificateContext(X509_ASN_ENCODING | PKCS_7_ASN_ENCODING, copy, cert->cbCertEncoded);
		coretest_check(bad != NULL && CryptoCertVerifySelfSigned(bad) == false, "a changed signature does not verify");
		CryptoCertFree(bad);
		HeapFree(GetProcessHeap(), 0, copy);
	}

	coretest_check(CryptoCertDeleteKey(cert) && CryptoCertHasKspKey(cert) == false, "the key deleted through the certificate");
	CryptoCertFree(cert);

	coretest_check(CryptoCertCreateSelfSigned(NULL, NULL, NULL, 30, scope) == NULL && CryptoCertCreateSelfSigned(L"CN=x", NULL, NULL, 0, scope) == NULL,
	               "no subject or 0 days is refused");
}

// The PKCS #12 file of OpenSSL 3 defaults imports with its key into the key storage provider;
// a wrong password, a cut file and bytes that are no PKCS #12 are refused
void pfx_test() {
	char thumbprint[2 * CRYPTO_THUMBPRINT_SIZE + 1];
	wchar_t cn[64];
	UCHAR junk[64];
	UINT scope = coretest_scope();

	coretest_info("scope: %s", coretest_scope_name());

	PCCERT_CONTEXT cert = CryptoCertImportPfx(coretest_pfx, coretest_pfx_size, CORETEST_PFX_PASSWORD, scope);
	if (coretest_check(cert != NULL, "PFX of OpenSSL 3 defaults (PBES2, PBKDF2-HMAC-SHA256, AES-256-CBC, SHA-256 MAC) imported") == false)
		return;

	coretest_check(CryptoCertThumbprintStr(cert, thumbprint, sizeof(thumbprint)) && strcmp(thumbprint, CORETEST_PFX_THUMBPRINT) == 0,
	               "thumbprint " CORETEST_PFX_THUMBPRINT);
	coretest_check(CertGetNameStringW(cert, CERT_NAME_ATTR_TYPE, 0, szOID_COMMON_NAME, cn, 64) > 1 && wcscmp(cn, L"ranz-pfx-test") == 0, "subject CN=ranz-pfx-test");
	coretest_check(CryptoCertVerifySelfSigned(cert), "the certificate (self-signed by OpenSSL) verifies");
	coretest_check(CryptoCertHasKspKey(cert), "the private key is in the CNG key storage provider (PKCS12_ALWAYS_CNG_KSP)");
	coretest_check(CryptoCertDeleteKey(cert) && CryptoCertHasKspKey(cert) == false, "the imported key deleted");
	CryptoCertFree(cert);

	coretest_check(CryptoCertImportPfx(coretest_pfx, coretest_pfx_size, L"wrong", scope) == NULL, "a wrong password is refused");
	coretest_check(CryptoCertImportPfx(coretest_pfx, coretest_pfx_size / 2, CORETEST_PFX_PASSWORD, scope) == NULL, "a cut file is refused");
	FillMemory(junk, sizeof(junk), 0x30);
	coretest_check(CryptoCertImportPfx(junk, sizeof(junk), CORETEST_PFX_PASSWORD, scope) == NULL && CryptoCertImportPfx(NULL, 0, NULL, scope) == NULL,
	               "bytes that are no PKCS #12 are refused");
}

// The store the Schannel server certificate is read from: LocalMachine\My for the service
// (elevated), the current user's My otherwise. The certificate is found by its thumbprint in the
// forms an operator copies, keeps its key in the store, and is removed again.
void certstore_test() {
	char thumbprint[2 * CRYPTO_THUMBPRINT_SIZE + 1];
	char spaced[3 * CRYPTO_THUMBPRINT_SIZE + 1];
	UINT scope = coretest_scope();

	coretest_info("scope: %s", coretest_scope_name());

	PCCERT_CONTEXT cert = CryptoCertCreateSelfSigned(L"CN=Ranz coretest store", NULL, NULL, 30, scope);
	if (coretest_check(cert != NULL && CryptoCertThumbprintStr(cert, thumbprint, sizeof(thumbprint)), "certificate created") == false) {
		CryptoCertFree(cert);
		return;
	}
	coretest_info("thumbprint %s", thumbprint);

	// "5a 68 38 ...": lower case with spaces, as certlm.msc shows it
	for (UINT i = 0; i < 2 * CRYPTO_THUMBPRINT_SIZE; i++) {
		char c = thumbprint[i];
		spaced[i + i / 2] = (char)((c >= 'A' && c <= 'F') ? c - 'A' + 'a' : c);
		if (i % 2 == 1)
			spaced[i + i / 2 + 1] = ' ';
	}
	spaced[3 * CRYPTO_THUMBPRINT_SIZE - 1] = 0;

	if (coretest_check(CryptoCertAddToStore(cert, NULL, scope), "added to the My store")) {
		PCCERT_CONTEXT found = CryptoCertFindByThumbprint(thumbprint, NULL, scope);
		coretest_check(found != NULL && found->cbCertEncoded == cert->cbCertEncoded && memcmp(found->pbCertEncoded, cert->pbCertEncoded, cert->cbCertEncoded) == 0,
		               "found by its thumbprint (40 hex digits)");
		coretest_check(found != NULL && CryptoCertHasKspKey(found), "the certificate from the store reaches its CNG key");
		CryptoCertFree(found);

		found = CryptoCertFindByThumbprint(spaced, L"My", scope);
		coretest_check(found != NULL, "found by its thumbprint in lower case with spaces");
		CryptoCertFree(found);

		coretest_check(CryptoCertFindByThumbprint("0000000000000000000000000000000000000000", NULL, scope) == NULL, "an unknown thumbprint finds nothing");
		coretest_check(CryptoCertRemoveFromStore(thumbprint, NULL, scope), "removed from the store");
		coretest_check(CryptoCertFindByThumbprint(thumbprint, NULL, scope) == NULL && CryptoCertRemoveFromStore(thumbprint, NULL, scope) == false,
		               "gone after the removal");
	}

	thumbprint[39] = 0;
	coretest_check(CryptoCertFindByThumbprint(thumbprint, NULL, scope) == NULL, "39 hex digits are refused");
	thumbprint[39] = 'G';
	coretest_check(CryptoCertFindByThumbprint(thumbprint, NULL, scope) == NULL && CryptoCertFindByThumbprint(NULL, NULL, scope) == NULL,
	               "a digit that is not hex, or no thumbprint, is refused");
	coretest_check(CryptoCertAddToStore(cert, L"RanzNoSuchStore", scope) == false, "a store that does not exist is not created");

	coretest_check(CryptoCertDeleteKey(cert), "the key deleted");
	CryptoCertFree(cert);
}
