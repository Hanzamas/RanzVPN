class PlanError(Exception):
    pass


class UF:
    def __init__(self):
        self.p = {}

    def find(self, x):
        self.p.setdefault(x, x)
        while self.p[x] != x:
            self.p[x] = self.p[self.p[x]]
            x = self.p[x]
        return x

    def union(self, a, b):
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            self.p[max(ra, rb)] = min(ra, rb)


def shadowed(name, code):
    """True when a function declares its own parameter or local variable called name."""
    pat = r"\b(?!(?:return|else|case|goto|sizeof|typedef|do)\b)[A-Za-z_]\w*(?:\s+|\s+\*+)" + re.escape(name) + r"\s*[=;,\[\)]"
    return re.search(pat, code) is not None


def members_of(code):
    return set(MEMBER.findall(code))


def wrap(text):
    return textwrap.fill(text, 72, break_long_words=False, break_on_hyphens=False)


def names_of(items, idxs):
    out = []
    for i in idxs:
        it = items[i]
        out.extend(it.all_names() if it.kind == "cond" else it.names)
    return out


def body_text(items, idxs, nl):
    """The moved items in source order. Items that touch in the source stay touching; any other two
    are separated by one blank line, and the first one by a blank line from what comes before it.
    The move-only checker compares blocks separated by blank lines, so this keeps them equal."""
    out = []
    prev = None
    for i in idxs:
        it = items[i]
        if prev is None or it.l0 != items[prev].l1 + 1:
            out.append(nl)
        out.append(it.text if it.text.endswith("\n") else it.text + nl)
        prev = i
    return "".join(out)


def drop_lines(lines, drop, after=None, include=None):
    """lines (a text split at "\\n") without the dropped ones; a blank line right after a dropped
    block goes too when the line kept before the block is blank, so no double blank lines are left
    behind, and the file keeps no more blank lines at its end than it had. With include, that line
    is inserted right after line index `after`. Only lines are deleted (and the one inserted), so
    the diff of the result is the dropped blocks and blank lines."""
    final = lines[-1] == ""  # the text ends with a newline: the last element is empty
    body = lines[:-1] if final else lines
    trailing = 0
    while trailing < len(body) and body[len(body) - 1 - trailing].strip() == "":
        trailing += 1
    keep = []
    for ln, t in enumerate(body):
        if ln not in drop and not (t.strip() == "" and (ln - 1) in drop and keep and keep[-1].strip() == ""):
            keep.append(t)
        if include is not None and ln == after:
            keep.append(include)
    k = 0
    while k < len(keep) and keep[len(keep) - 1 - k].strip() == "":
        k += 1
    if k > trailing:
        del keep[len(keep) - (k - trailing):]
    if final:
        keep.append("")
    return keep


def god_text(lines, drop, after, include):
    """The god file without the dropped lines, with the include line (when given) inserted right
    after line index `after` (the last line of its preamble)."""
    return "\n".join(drop_lines(lines, drop, after, include))


def with_include(text, inc_line, name, nl):
    """text with inc_line right after the last line of its preamble, unless it includes name already."""
    if re.search(r'^\s*#\s*include\s+"' + re.escape(name) + '"', text, re.M):
        return text
    f = S.CFile(text=text, path="<mem>")
    pl = f.prologue_lines()
    if pl == 0:
        raise PlanError(f"no include block to add {inc_line} to")
    a = f.starts[pl] if pl < len(f.starts) else len(text)
    if a == len(text) and not text.endswith("\n"):
        return text + nl + inc_line + nl
    return text[:a] + inc_line + nl + text[a:]


def cur(vfs, path):
    if path in vfs:
        return vfs[path]
    if os.path.isfile(path):
        return S.read_text(path)
    return None


class Step:
    """One commit: kind is split, header or linkage."""

    def __init__(self, kind, subject, body, writes, moved=0):
        self.kind = kind
        self.subject = subject
        self.body = body
        self.writes = writes
        self.moved = moved

