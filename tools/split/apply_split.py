"""Split the god files of Ranz VPN by responsibility, as tools/split/split-map.json says (issue #29).

Usage (from the repository root):
    python -I tools/split/apply_split.py [--map FILE] [--module Hub] [--dry-run] [--explain]
                                         [--commit [--linkage]] [--drift-json FILE] [--reference REV]

What it does, for each module of the map:
  1. Parses the god file into top-level items (splitlib.py) and assigns each item a destination
     file from the map: explicit names first, then the first matching pattern.
  2. Keeps every file-local symbol with all of its users. A static function or variable, a
     function or variable that no included header declares, and a prototype written in the .c
     file can only be seen from the file that holds it, so the items that use one are joined into
     a group that moves as a whole. A group whose members the map sends to different files stays
     in the god file, with a warning: the build would fail otherwise.
  3. Places the file's own macros, types and extern declarations ("hoistables") next to their
     users: in the one file that uses them, or in the module-internal header <Module>Internal.h
     when several files of the module do.
  4. Moves every item verbatim, with the comment written directly above it, in its original
     order. A new file starts with the god file's comment header style and the preprocessor
     lines of its preamble that the moved code needs (comment lines of the preamble are left out).
  5. Moves the prototypes that only the module's own files use from the API header (the god
     file's same-named header) to the module-internal header, which every file of the module
     includes at the end of its preamble.
  6. Optionally (--linkage) makes static every function that only its own file uses, and deletes
     its prototype from the module's headers.
  7. Reports every item that the map does not place (it stays in the god file), every group
     kept back by a file-local tie, and every map name that matches nothing.

The work of one module is a sequence of steps, each one commit of a #29 kind:
  split:   the shared macros and types, from the god file to the NEW <Module>Internal.h (with an
           include guard); the god file gains only the one #include of it (#29 open question 12 (a));
  split:   one commit per destination file of the map, in map order;
  header:  the prototypes that only the module uses, from <Module>.h to <Module>Internal.h (when
           the header is new here, every .c file of the module gains its #include);
  linkage: (--linkage only) static for the functions that one file uses, their prototypes deleted.
Without --commit the tool writes the final state of every step. With --commit it writes each step
as its own git commit (footer "Refs #29") and runs the move-only checker
(.github/scripts/move-only-check.py) on each commit; it stops at the first failure and leaves the
commits made so far in place. --dry-run writes nothing and lists the commits it would make.

No CMake edit is made: Cedar and Mayaqua glob *.c, so new files need none.

The tree can drift from the map. A map name or pattern that matches no definition (deleted or
renamed since the map was written) is reported with the closest unmapped names, and places
nothing. A module whose god file is missing or does not parse is reported and skipped; the other
modules are still split. --drift-json FILE writes the drift of every module as JSON. --reference
REV lists the definitions that land in a different file than in the split commit REV (for example
a function that an #if region used to carry along).
"""
